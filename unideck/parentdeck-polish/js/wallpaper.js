/* TDWallpaper — animated wallpapers for premium themes (13 Nov 2026).
 *
 * A theme pack names a shader and its colours (`wallpaper: { shader, colors, speed, scale }`, checked by
 * StoreCore.validateStorePack); the shader code lives here, in the app, never in a pack. Plain WebGL 1, no libraries,
 * no eval and no inline script, so it runs under the extension's default Content Security Policy.
 *
 *   TDWallpaper.mount(spec, opts) -> boolean   draws spec behind the app (false: no WebGL, the CSS gradient stays)
 *   TDWallpaper.unmount()                      removes it (the theme's static gradient shows again)
 *   TDWallpaper.pause(on)                      holds the picture still (e.g. while a timer runs)
 *
 * Kind to the classroom computer: the pixel ratio is capped (1.5) and so is the pixel count (about 1.6 million),
 * and the resolution steps down (to 40% at most) when frames come slower than about 20 a second;
 * nothing draws while the tab is hidden or paused; prefers-reduced-motion gets one still frame, redrawn only on resize.
 * Without WebGL (or if the context is lost) the canvas goes away and the theme's CSS gradient underneath shows.
 *
 * ---------------------------------------------------------------------------------------------------------------
 * Shader credits (the comments from the original snippets are kept with each shader below):
 *  - "Glass Fold": from GradFlow, animated WebGL gradients for React — https://gradflow.meerbahadin.dev
 *  - "Fluted Glass": generated by the 21st.dev Shader Builder, adapted from Paper Shaders —
 *    https://shaders.paper.design/fluted-glass — Paper Shaders is licensed under the Apache License, Version 2.0
 *    (http://www.apache.org/licenses/LICENSE-2.0).
 * Changes made here (Apache-2.0 §4b): ported from React/TypeScript to plain JavaScript; the Fluted Glass cursor
 * effects, blur, hue, vignette and OKLab branches the preset leaves off were removed; colours, speed and scale come
 * from the theme pack; render loop rewritten for TeachersDeck (pixel caps, pause, reduced motion, fallback).
 * ---------------------------------------------------------------------------------------------------------------
 */
(function (root) {
  'use strict';

  var VERTEX = 'attribute vec2 position;\nvarying vec2 vUv;\nvoid main() {\n  vUv = position * 0.5 + 0.5;\n  gl_Position = vec4(position, 0.0, 1.0);\n}\n';
  var PRECISION = '#ifdef GL_FRAGMENT_PRECISION_HIGH\nprecision highp float;\n#else\nprecision mediump float;\n#endif\n';

  /* ---- Glass Fold — From GradFlow, animated WebGL gradients for React: https://gradflow.meerbahadin.dev ---- */
  var GLASS_FOLD = PRECISION + [
    'uniform float u_time;',
    'uniform vec3 u_color1;   // the body of each glass pane',
    'uniform vec3 u_color2;   // the background',
    'uniform vec3 u_color3;   // the lit edges',
    'uniform float u_scale;',
    'uniform float u_noise;',
    'uniform vec2 u_resolution;',
    'varying vec2 vUv;',
    'float grain(vec2 st) { return fract(sin(dot(st, vec2(12.9898, 78.233))) * 43758.5453); }',
    '// centered coordinates, y in [-0.5, 0.5], x stretched by the aspect ratio',
    'vec2 centered(vec2 uv) { vec2 p = uv - 0.5; p.x *= u_resolution.x / max(u_resolution.y, 1.0); return p; }',
    'mat2 rot(float a) { float s = sin(a); float c = cos(a); return mat2(c, -s, s, c); }',
    '// panes of glass folded over each other. Each pane has one creased edge',
    '// that catches the light and thins out to nothing behind it; panes screen',
    '// over one another, so overlaps get brighter instead of darker.',
    'vec3 shade(vec2 uv, float time) {',
    '  vec2 q = rot(0.6) * centered(uv) * 2.0 * u_scale;',
    '  float t = time * 0.6;',
    '  float pixel = 2.0 * u_scale / max(u_resolution.y, 1.0);',
    '  vec3 color = mix(u_color2, u_color2 * 0.45, clamp(length(centered(uv)) * 1.3, 0.0, 1.0));',
    '  for (int i = 0; i < 6; i++) {',
    '    float fi = float(i);',
    '    float bend = mod(fi, 2.0) * 2.0 - 1.0;',
    '    float crease = (fi - 2.5) * 0.4 + 0.26 * sin(q.x * (1.05 + 0.12 * fi) + fi * 1.9 + t * (0.25 + 0.05 * fi)) + 0.1 * bend * q.x * q.x;',
    '    float s = q.y - crease;',
    '    float pane = smoothstep(-pixel, pixel, s);',
    '    float back = max(s, 0.0);',
    '    // thick near the crease, clear further in',
    '    float body = exp(-back * 1.7);',
    '    float fresnel = exp(-back * 8.0);',
    '    // the lit edge, and a fainter line just inside it for the glass\'s thickness',
    '    float rim = exp(-back * 80.0);',
    '    float inner = exp(-pow((back - 0.045) / 0.014, 2.0));',
    '    float bloom = exp(-abs(s) * 20.0);',
    '    vec3 tint = mix(u_color1, u_color3, clamp(fresnel * 0.6 + 0.08 + 0.14 * sin(fi * 2.1 + q.x * 0.8 + t * 0.2), 0.0, 1.0));',
    '    vec3 light = tint * pane * (body * 0.42 + fresnel * 0.4) + u_color3 * (pane * (rim * 0.6 + inner * 0.12) + bloom * 0.1);',
    '    // screen blend',
    '    color += light * (1.0 - color);',
    '  }',
    '  return clamp(color, 0.0, 1.0);',
    '}',
    'void main() {',
    '  vec3 color = shade(vUv, u_time);',
    '  if (u_noise > 0.001) { float g = grain(vUv * 200.0 + u_time * 0.1); color *= 1.0 - u_noise * 0.4 + u_noise * g * 0.4; }',
    '  gl_FragColor = vec4(color, 1.0);',
    '}'].join('\n');

  /* ---- Fluted Glass — ShaderBackground generated by the 21st.dev Shader Builder ("Fluted Glass").
     Adapted from Paper Shaders: https://shaders.paper.design/fluted-glass
     Paper Shaders is licensed under Apache-2.0. ---- */
  var FLUTED_GLASS = PRECISION + [
    'uniform vec3 u_colors[8];',
    'uniform vec4 u_scene;      // resolution.xy, time, colour count',
    'uniform vec4 u_shape;      // scale, intensity, paramA, warp',
    'uniform vec4 u_surface;    // detail, contrast, brightness, saturation',
    'uniform vec4 u_finish;     // grain, seed, rotation, unused',
    '#define u_resolution u_scene.xy',
    '#define u_time u_scene.z',
    '#define u_colorCount u_scene.w',
    '#define u_scale u_shape.x',
    '#define u_intensity u_shape.y',
    '#define u_paramA u_shape.z',
    '#define u_warp u_shape.w',
    '#define u_detail u_surface.x',
    '#define u_contrast u_surface.y',
    '#define u_brightness u_surface.z',
    '#define u_saturation u_surface.w',
    '#define u_grain u_finish.x',
    '#ifdef GL_FRAGMENT_PRECISION_HIGH',
    '#define u_seed u_finish.y',
    '#else',
    '// Keep hash inputs inside mediump\'s guaranteed ±2^14 range.',
    '#define u_seed mod(u_finish.y, 31.0)',
    '#endif',
    '#define u_rotate u_finish.z',
    'float hash21(vec2 p) {',
    '#ifndef GL_FRAGMENT_PRECISION_HIGH',
    '  p = mod(p, 31.0);',
    '#endif',
    '  p = fract(p * vec2(234.34, 435.345));',
    '  p += dot(p, p + 34.23);',
    '  return fract(p.x * p.y);',
    '}',
    '// Even, un-structured white noise for film grain (Dave Hoskins hash12). The',
    '// multiply hash above is fine for value noise but shows a faint axis-aligned',
    '// mesh at integer fragment coords, which reads as a net over flat areas.',
    'float grainHash(vec2 p) {',
    '  vec3 p3 = fract(vec3(p.xyx) * 0.1031);',
    '  p3 += dot(p3, p3.yzx + 33.33);',
    '  return fract((p3.x + p3.y) * p3.z);',
    '}',
    'float noise(vec2 p) {',
    '  vec2 i = floor(p);',
    '  vec2 f = fract(p);',
    '  vec2 u = f * f * (3.0 - 2.0 * f);',
    '  return mix(mix(hash21(i), hash21(i + vec2(1.0, 0.0)), u.x), mix(hash21(i + vec2(0.0, 1.0)), hash21(i + vec2(1.0, 1.0)), u.x), u.y);',
    '}',
    'float fbm(vec2 p) {',
    '  float v = 0.0;',
    '  float a = 0.5;',
    '  for (int i = 0; i < 5; i++) { v += a * noise(p); p = p * 2.03 + vec2(17.0, 9.2); a *= 0.5; }',
    '  return v;',
    '}',
    '// Mix through the recipe colours; x is clamped to 0..1. WebGL1 forbids',
    '// dynamic uniform indexing in fragment shaders, hence the constant loop.',
    'vec3 palette(float x) {',
    '  float n = max(u_colorCount - 1.0, 1.0);',
    '  float f = clamp(x, 0.0, 1.0) * n;',
    '  vec3 col = u_colors[0];',
    '  for (int i = 0; i < 7; i++) {',
    '    if (float(i) < n) col = mix(col, u_colors[i + 1], smoothstep(0.0, 1.0, clamp(f - float(i), 0.0, 1.0)));',
    '  }',
    '  return col;',
    '}',
    'vec3 shade(vec2 p, float t) {',
    '  float flutes = mix(42.0, 7.0, u_paramA);',
    '  float cell = fract((p.x + 1.0) * flutes) - 0.5;',
    '  float prism = sin(cell * 3.1415926) * (0.03 + u_intensity * 0.2);',
    '  vec2 samplePoint = p + vec2(prism, sin(p.x * flutes + t * 0.2) * prism * 0.35);',
    '  float field = fbm(samplePoint * 2.2 + vec2(t * 0.035, -t * 0.025) + u_seed);',
    '  field += 0.24 * sin(samplePoint.y * 3.0 + samplePoint.x * 1.3);',
    '  float highlight = pow(1.0 - abs(cell) * 2.0, mix(12.0, 2.0, u_intensity));',
    '  float shadow = smoothstep(0.18, 0.5, abs(cell));',
    '  vec3 glass = palette(clamp(field + highlight * 0.3, 0.0, 1.0));',
    '  return glass * (0.72 + highlight * 0.42 - shadow * 0.12);',
    '}',
    'void main() {',
    '  vec2 p = (gl_FragCoord.xy - 0.5 * u_resolution.xy) / min(u_resolution.x, u_resolution.y);',
    '  p *= u_scale;',
    '  // Field transform: rotate.',
    '  if (abs(u_rotate) > 0.0001) { float cr = cos(u_rotate), sr = sin(u_rotate); p = mat2(cr, -sr, sr, cr) * p; }',
    '  // Organic domain warp.',
    '  if (u_warp > 0.0) p += u_warp * (vec2(fbm(p * u_detail + u_seed), fbm(p * u_detail + vec2(5.2, 1.3))) - 0.5);',
    '  vec3 col = shade(p, u_time);',
    '  // Post: contrast, saturation, brightness, grain.',
    '  if (abs(u_contrast - 1.0) > 0.0001) col = (col - 0.5) * u_contrast + 0.5;',
    '  if (abs(u_saturation - 1.0) > 0.0001) { float luma = dot(col, vec3(0.299, 0.587, 0.114)); col = mix(vec3(luma), col, u_saturation); }',
    '  if (abs(u_brightness) > 0.0001) col += u_brightness;',
    '  if (u_grain > 0.0001) col += (grainHash(gl_FragCoord.xy + vec2(u_seed * 17.0, u_seed * 31.0)) - 0.5) * u_grain;',
    '  gl_FragColor = vec4(clamp(col, 0.0, 1.0), 1.0);',
    '}'].join('\n');

  function hexToVec3(hex) {
    var n = parseInt(String(hex).replace('#', ''), 16) || 0;
    return [((n >> 16) & 255) / 255, ((n >> 8) & 255) / 255, (n & 255) / 255];
  }

  /* Each shader: its source, and how a theme's { colors, scale } becomes uniforms. The fixed numbers are the
     original presets' (Glass Fold's demo settings; the 21st.dev "Fluted Glass" recipe). */
  var SHADERS = {
    'glass-fold': {
      frag: GLASS_FOLD,
      uniforms: ['u_time', 'u_color1', 'u_color2', 'u_color3', 'u_scale', 'u_noise', 'u_resolution'],
      setup: function (gl, u, w) {
        var c = w.colors;
        gl.uniform3fv(u.u_color1, hexToVec3(c[0]));
        gl.uniform3fv(u.u_color2, hexToVec3(c[1]));
        gl.uniform3fv(u.u_color3, hexToVec3(c[2] || c[0]));
        gl.uniform1f(u.u_scale, w.scale);
        gl.uniform1f(u.u_noise, 0.12);
      },
      frame: function (gl, u, t, wd, ht) { gl.uniform1f(u.u_time, t); gl.uniform2f(u.u_resolution, wd, ht); },
    },
    'fluted-glass': {
      frag: FLUTED_GLASS,
      uniforms: ['u_colors', 'u_scene', 'u_shape', 'u_surface', 'u_finish'],
      setup: function (gl, u, w) {
        var flat = [];
        for (var i = 0; i < 8; i++) flat = flat.concat(hexToVec3(w.colors[Math.min(i, w.colors.length - 1)]));
        gl.uniform3fv(u.u_colors, new Float32Array(flat));
        gl.uniform4f(u.u_shape, w.scale, 0.52, 0.51, 0.186);           // scale, intensity, paramA, warp
        gl.uniform4f(u.u_surface, 2.752, 1.005, 0.0, 1.0);             // detail, contrast, brightness, saturation
        gl.uniform4f(u.u_finish, 0.032, 1.0, 0.6458, 0.0);             // grain, seed, rotation
        this.count = w.colors.length;
      },
      frame: function (gl, u, t, wd, ht) { gl.uniform4f(u.u_scene, wd, ht, t, this.count); },
    },
  };

  var MAX_DPR = 1.5, MAX_PIXELS = 1600000, STILL_TIME = 6.0;
  var cur = null, paused = false;

  function reduceMotion() { return !!(root.matchMedia && root.matchMedia('(prefers-reduced-motion: reduce)').matches); }

  function compile(gl, type, src) {
    var s = gl.createShader(type);
    gl.shaderSource(s, src);
    gl.compileShader(s);
    if (!gl.getShaderParameter(s, gl.COMPILE_STATUS)) { var log = gl.getShaderInfoLog(s); gl.deleteShader(s); throw new Error(log || 'shader'); }
    return s;
  }

  function mount(spec, opts) {
    unmount();
    opts = opts || {};
    var def = spec && SHADERS[spec.shader];
    if (!def || !Array.isArray(spec.colors) || spec.colors.length < 2) return false;
    var canvas = document.createElement('canvas');
    canvas.className = 'td-wallpaper';
    canvas.setAttribute('aria-hidden', 'true');
    var gl = null;
    try { gl = canvas.getContext('webgl', { antialias: false, alpha: false, depth: false, stencil: false, powerPreference: 'low-power', preserveDrawingBuffer: false }); } catch (e) { gl = null; }
    if (!gl) return false;   // no WebGL: the theme's CSS gradient stays

    var program, buffer, u = {};
    try {
      var vs = compile(gl, gl.VERTEX_SHADER, VERTEX), fs = compile(gl, gl.FRAGMENT_SHADER, def.frag);
      program = gl.createProgram();
      gl.attachShader(program, vs); gl.attachShader(program, fs);
      gl.linkProgram(program);
      gl.deleteShader(vs); gl.deleteShader(fs);
      if (!gl.getProgramParameter(program, gl.LINK_STATUS)) throw new Error(gl.getProgramInfoLog(program) || 'link');
      gl.useProgram(program);
      buffer = gl.createBuffer();
      gl.bindBuffer(gl.ARRAY_BUFFER, buffer);
      gl.bufferData(gl.ARRAY_BUFFER, new Float32Array([-1, -1, 3, -1, -1, 3]), gl.STATIC_DRAW);   // one triangle covers the screen
      var loc = gl.getAttribLocation(program, 'position');
      gl.enableVertexAttribArray(loc);
      gl.vertexAttribPointer(loc, 2, gl.FLOAT, false, 0, 0);
      def.uniforms.forEach(function (n) { u[n] = gl.getUniformLocation(program, n); });
      def.setup(gl, u, spec);
    } catch (e) {
      if (root.console) console.warn('TeachersDeck: wallpaper off (' + spec.shader + ')', e && e.message);
      var lose = gl.getExtension('WEBGL_lose_context'); if (lose) lose.loseContext();
      return false;
    }

    var host = opts.host || document.body;
    if (opts.before && opts.before.parentNode) opts.before.parentNode.insertBefore(canvas, opts.before);
    else host.appendChild(canvas);

    var speed = typeof spec.speed === 'number' ? spec.speed : 0.5;
    var elapsed = STILL_TIME, last = null, raf = 0, still = reduceMotion(), dead = false, frames = 0;
    var quality = 1, slow = 0;   // drops the resolution on a slow computer (frames over ~45 ms), never below 40%

    function resize() {
      var dpr = Math.min(root.devicePixelRatio || 1, MAX_DPR);
      var w = Math.max(1, Math.round(canvas.clientWidth * dpr)), h = Math.max(1, Math.round(canvas.clientHeight * dpr));
      var k = Math.min(1, Math.sqrt(MAX_PIXELS / (w * h))) * quality;
      w = Math.max(1, Math.round(w * k)); h = Math.max(1, Math.round(h * k));
      if (canvas.width !== w || canvas.height !== h) { canvas.width = w; canvas.height = h; }
      gl.viewport(0, 0, w, h);
    }
    function draw() {
      resize();
      def.frame(gl, u, elapsed, canvas.width, canvas.height);
      gl.drawArrays(gl.TRIANGLES, 0, 3);
      frames++;
    }
    function running() { return !dead && !still && !paused && document.visibilityState !== 'hidden'; }
    function loop(now) {
      raf = 0;
      if (!running()) { last = null; return; }
      // speed accumulates over time, so a pause or a slow frame never makes the pattern jump
      if (last !== null) {
        var dt = (now - last) / 1000;
        elapsed += Math.min(dt, 0.1) * speed;
        slow = dt > 0.045 ? slow + 1 : Math.max(0, slow - 1);
        if (slow > 20 && quality > 0.4) { quality = Math.max(0.4, quality * 0.8); slow = 0; }
      }
      last = now;
      draw();
      raf = root.requestAnimationFrame(loop);
    }
    function kick() {
      if (dead) return;
      if (running()) { if (!raf) raf = root.requestAnimationFrame(loop); }
      else { if (raf) { root.cancelAnimationFrame(raf); raf = 0; } last = null; }
    }
    function onVisibility() { kick(); }
    var mq = root.matchMedia ? root.matchMedia('(prefers-reduced-motion: reduce)') : null;
    function onMotion() { still = reduceMotion(); if (still) draw(); kick(); }
    var ro = root.ResizeObserver ? new ResizeObserver(function () { if (!running()) draw(); }) : null;
    function onLost(e) { e.preventDefault(); unmount(); }   // context lost: back to the CSS gradient

    document.addEventListener('visibilitychange', onVisibility);
    if (mq) { if (mq.addEventListener) mq.addEventListener('change', onMotion); else if (mq.addListener) mq.addListener(onMotion); }
    if (ro) ro.observe(canvas); else root.addEventListener('resize', draw);
    canvas.addEventListener('webglcontextlost', onLost);

    draw();          // the still frame shows at once (and is all a reduced-motion user gets)
    canvas.classList.add('on');
    kick();

    cur = {
      canvas: canvas, kick: kick, draw: draw,
      info: function () { return { shader: spec.shader, running: running(), still: still, paused: paused, frames: frames, width: canvas.width, height: canvas.height, quality: quality }; },
      stop: function () {
        dead = true;
        if (raf) root.cancelAnimationFrame(raf);
        document.removeEventListener('visibilitychange', onVisibility);
        if (mq) { if (mq.removeEventListener) mq.removeEventListener('change', onMotion); else if (mq.removeListener) mq.removeListener(onMotion); }
        if (ro) ro.disconnect(); else root.removeEventListener('resize', draw);
        canvas.removeEventListener('webglcontextlost', onLost);
        try { gl.deleteBuffer(buffer); gl.deleteProgram(program); var lose = gl.getExtension('WEBGL_lose_context'); if (lose) lose.loseContext(); } catch (e) { /* already gone */ }
        canvas.remove();
      },
    };
    return true;
  }

  function unmount() { if (cur) { var c = cur; cur = null; c.stop(); } }
  function pause(on) { paused = !!on; if (cur) cur.kick(); }
  function active() { return !!cur; }
  function info() { return cur ? cur.info() : null; }   // for tests: what is drawing and how often

  root.TDWallpaper = { mount: mount, unmount: unmount, pause: pause, active: active, info: info, SHADERS: Object.keys(SHADERS), MAX_DPR: MAX_DPR };
})(typeof window !== 'undefined' ? window : this);
